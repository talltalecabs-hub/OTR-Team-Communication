// Build a reviewable, one-time SQL replacement; this script never connects to Supabase.
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const source=JSON.parse(readFileSync(join(root,"data/inventory/f22-e92-2026-11-08.json"),"utf8"));
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
const bins=source.bins.map(bin=>({...bin,derived_parent:false}));
for(const parent of new Set(bins.map(bin=>bin.parent_bin_code))){
  if(bins.some(bin=>bin.bin_code===parent)) continue;
  const children=bins.filter(bin=>bin.parent_bin_code===parent);
  bins.push({
    platform:children[0].platform,bin_code:parent,parent_bin_code:parent,
    description:children[0].description.split(" · ")[0],
    tagged_entries:children.reduce((total,bin)=>total+bin.tagged_entries,0),
    stock_status:"Parent bin / sub-bins listed",source_reference:"Parent relationship in workbook",
    source_row:null,derived_parent:true
  });
}
bins.sort((a,b)=>a.bin_code.localeCompare(b.bin_code));

if(source.snapshot_id!=="f22-e92-2026-11-08" || source.parts.length!==215 || source.bins.length!==43 || bins.length!==45){
  throw new Error("Unexpected workbook snapshot dimensions");
}
if(new Set(source.parts.map(item=>item.inventory_code)).size!==215 ||
  source.parts.some(item=>!['F22','E92'].includes(item.platform) ||
    (item.quantity!==null && (!Number.isInteger(item.quantity)||item.quantity<0)))){
  throw new Error("Invalid or duplicate workbook part identity/count");
}

const sql=`-- GENERATED by node scripts/build_inventory_update.mjs; do not hand edit.
-- Source: ${source.source_file}
-- SHA-256: ${source.source_sha256}
-- PREPARED ONLY. No production migration or inventory write has been performed.
-- Prerequisites: schema.sql, label_assistant_schema.sql, inventory_count_schema.sql.
-- Replaces only F22, E92 and the old M235 / M235iR inventory group.
-- Original target rows and overwritten bins are archived privately before replacement.
-- Rerunning this snapshot is a no-op, preserving subsequent crew edits.
begin;

lock table public.inventory_items, public.inventory_bins in share row exclusive mode;

create schema if not exists otr_inventory_archive;
revoke all on schema otr_inventory_archive from public, anon, authenticated;

create table if not exists otr_inventory_archive.replacement_batches (
  snapshot_id text primary key,
  source_sha256 text not null,
  source_snapshot jsonb not null,
  applied_at timestamptz not null default now()
);
create table if not exists otr_inventory_archive.inventory_items (
  snapshot_id text not null references otr_inventory_archive.replacement_batches(snapshot_id),
  inventory_item_id uuid not null,
  original_row jsonb not null,
  primary key(snapshot_id,inventory_item_id)
);
create table if not exists otr_inventory_archive.inventory_bins (
  snapshot_id text not null references otr_inventory_archive.replacement_batches(snapshot_id),
  inventory_bin_id uuid not null,
  original_row jsonb not null,
  primary key(snapshot_id,inventory_bin_id)
);
alter table otr_inventory_archive.replacement_batches enable row level security;
alter table otr_inventory_archive.inventory_items enable row level security;
alter table otr_inventory_archive.inventory_bins enable row level security;
revoke all on all tables in schema otr_inventory_archive from public, anon, authenticated;

do $inventory_update$
declare
  v_source jsonb := ${quote(JSON.stringify(source))}::jsonb;
  v_bins jsonb := ${quote(JSON.stringify(bins))}::jsonb;
  v_snapshot_id text := ${quote(source.snapshot_id)};
  v_source_sha256 text := ${quote(source.source_sha256)};
  v_other_inventory_before jsonb;
  v_other_inventory_after jsonb;
  v_registry_before jsonb;
  v_registry_after jsonb;
  v_count integer;
begin
  if exists(select 1 from otr_inventory_archive.replacement_batches where snapshot_id=v_snapshot_id) then
    if exists(select 1 from otr_inventory_archive.replacement_batches where snapshot_id=v_snapshot_id and source_sha256<>v_source_sha256) then
      raise exception 'Snapshot ID already exists with a different workbook hash';
    end if;
    raise notice 'Snapshot % already applied; no inventory changed',v_snapshot_id;
    return;
  end if;

  -- Abort if a workbook Bin ID is already owned by a different chassis.
  if exists(
    select 1 from public.inventory_bins b
    join jsonb_array_elements(v_bins) incoming on b.bin_code=incoming->>'bin_code'
    where b.model is distinct from incoming->>'platform'
  ) then
    raise exception 'Workbook Bin ID conflicts with an existing bin chassis';
  end if;

  select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]'::jsonb)
    into v_other_inventory_before from public.inventory_items i
    where i.platform is null or i.platform not in ('F22','E92','M235 / M235iR');
  select coalesce(jsonb_agg(to_jsonb(v) order by v.vehicle_code),'[]'::jsonb)
    into v_registry_before from public.vehicles v;

  insert into otr_inventory_archive.replacement_batches(snapshot_id,source_sha256,source_snapshot)
    values(v_snapshot_id,v_source_sha256,v_source);
  insert into otr_inventory_archive.inventory_items(snapshot_id,inventory_item_id,original_row)
    select v_snapshot_id,id,to_jsonb(i) from public.inventory_items i
    where platform in ('F22','E92','M235 / M235iR');
  insert into otr_inventory_archive.inventory_bins(snapshot_id,inventory_bin_id,original_row)
    select v_snapshot_id,b.id,to_jsonb(b) from public.inventory_bins b
    where b.bin_code in(select incoming->>'bin_code' from jsonb_array_elements(v_bins) incoming);

  delete from public.inventory_items where platform in ('F22','E92','M235 / M235iR');

  insert into public.inventory_bins(
    bin_code,make,make_prefix,model,system,description,label_format,qr_value,status,source_metadata
  )
    select incoming->>'bin_code','BMW','B',incoming->>'platform',incoming->>'description',
      incoming->>'description','4x6','OTR:BIN:'||(incoming->>'bin_code'),'Active',
      incoming || jsonb_build_object('snapshot_id',v_snapshot_id,'source_file',v_source->>'source_file')
    from jsonb_array_elements(v_bins) incoming
    on conflict(bin_code) do update set
      make=excluded.make,make_prefix=excluded.make_prefix,model=excluded.model,
      system=excluded.system,description=excluded.description,label_format=excluded.label_format,
      qr_value=excluded.qr_value,status=excluded.status,source_metadata=excluded.source_metadata;

  update public.inventory_bins child set parent_bin_id=parent.id
    from jsonb_array_elements(v_bins) incoming,public.inventory_bins parent
    where child.bin_code=incoming->>'bin_code'
      and parent.bin_code=incoming->>'parent_bin_code'
      and child.id<>parent.id;

  insert into public.inventory_items(
    inventory_code,platform,location,category,item_name,quantity,condition,status,notes,source,
    verification_status,original_quantity,original_item_text,original_location,part_number,
    compatibility,assignment_type,inventory_bin_id,quantity_unit,source_metadata
  )
    select incoming->>'inventory_code',incoming->>'platform',incoming->>'bin_code',incoming->>'category',
      incoming->>'item_name',(incoming->>'quantity')::integer,incoming->>'condition',
      case when incoming->>'quantity' is null then 'Uncounted'
           when (incoming->>'quantity')::integer=0 then 'Out of Stock' else 'In Stock' end,
      incoming->>'label_note',v_source->>'source_file',
      case when (incoming->>'quantity')::integer=0 then 'Consumed/Removed' else 'Imported' end,
      (incoming->>'quantity')::integer,incoming->>'label_text',incoming->>'bin_code',incoming->>'part_number',
      incoming->'compatibility','General Inventory',b.id,incoming->>'quantity_unit',
      incoming || jsonb_build_object('snapshot_id',v_snapshot_id,'source_file',v_source->>'source_file')
    from jsonb_array_elements(v_source->'parts') incoming
    join public.inventory_bins b on b.bin_code=incoming->>'bin_code';

  get diagnostics v_count = row_count;
  if v_count<>215 then raise exception 'Expected 215 source labels, inserted %',v_count; end if;
  if (select count(*) from public.inventory_items where platform='F22')<>92 or
     (select count(*) from public.inventory_items where platform='E92')<>123 or
     (select count(*) from public.inventory_items where platform in ('F22','E92') and quantity is null)<>5 then
    raise exception 'Workbook chassis or unknown-count totals do not match';
  end if;

  select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]'::jsonb)
    into v_other_inventory_after from public.inventory_items i
    where i.platform is null or i.platform not in ('F22','E92','M235 / M235iR');
  select coalesce(jsonb_agg(to_jsonb(v) order by v.vehicle_code),'[]'::jsonb)
    into v_registry_after from public.vehicles v;
  if v_other_inventory_before<>v_other_inventory_after or v_registry_before<>v_registry_after then
    raise exception 'Unrelated inventory or vehicle registry changed; replacement rolled back';
  end if;
end;
$inventory_update$;

commit;
`;
const output=join(root,"supabase/update_inventory_f22_e92_20261108.sql");
if(process.argv.includes("--check")){
  if(readFileSync(output,"utf8")!==sql) throw new Error("Generated inventory update is stale");
  console.log("PASS generated F22/E92 inventory SQL matches canonical workbook snapshot");
}else{
  writeFileSync(output,sql);
  console.log("Prepared F22/E92 inventory update: 215 labels, 45 bin nodes (39 numbered parents)");
}
