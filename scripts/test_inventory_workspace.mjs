// Isolated PostgreSQL checks. No production connection or browser persistence.
import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {randomUUID} from 'node:crypto';
const {PGlite}=await import(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(join(root,p),'utf8');
const migration=suffix=>'supabase/migrations/'+readdirSync(join(root,'supabase/migrations')).find(n=>n.endsWith(suffix));
const db=new PGlite();
const one=async(q,p=[])=>(await db.query(q,p)).rows[0];
const rows=async(q,p=[])=>(await db.query(q,p)).rows;
const snapshot=async()=>one("select (select md5(string_agg(to_jsonb(i)::text,'' order by id)) from inventory_items i) as items,(select md5(string_agg(to_jsonb(b)::text,'' order by id)) from inventory_bins b) as bins,(select md5(string_agg(to_jsonb(v)::text,'' order by vehicle_code)) from vehicles v) as vehicles");
const call=async(q,p=[])=>{await db.exec('set role anon');try{return await one(q,p);}finally{await db.exec('reset role');}};
const save=async(id,revision,changes,actor='jd')=>(await call('select save_inventory_workspace_draft($1,$2,$3,$4) as result',[id,revision,changes,actor])).result;
const duplicate=async(source,id,actor='jd')=>(await call('select duplicate_inventory_workspace_draft($1,$2,$3) as result',[source,id,actor])).result;
const commit=async(id,revision,actor='jd')=>(await call('select commit_inventory_workspace_draft($1,$2,$3) as result',[id,revision,actor])).result;
const counts=()=>one('select (select count(*)::int from inventory_items) as stock,(select count(*)::int from inventory_events) as stock_events,(select count(*)::int from inventory_workspace_drafts) as drafts,(select count(*)::int from inventory_workspace_events) as draft_events');
try{
  await db.exec('create role anon;create role authenticated;');
  for(const f of ['schema.sql','vehicles_schema.sql','seed_inventory.sql','label_assistant_schema.sql','inventory_count_schema.sql','inventory_stock_category_schema.sql','update_inventory_f22_e92_20261108.sql','e92_cart_assignments.sql'])await db.exec(read('supabase/'+f));
  await db.exec(read(migration('_inventory_crew_workflow.sql')));
  await db.exec("create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]); create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,unique(bucket_id,name)); alter table storage.objects enable row level security; grant usage on schema storage to anon; grant select,insert on storage.objects to anon;");
  const before=await snapshot();
  await db.exec(read(migration('_inventory_creation_workspace.sql')));
  assert.deepEqual(await snapshot(),before);
  assert.equal((await one("select public from storage.buckets where id='otr-inventory-workspace'")).public,false);
  const initial=await counts();
  const id=randomUUID();
  await assert.rejects(save(id,0,{},'   '),/Initials/);
  let card=await save(id,0,{x:1200,y:1400,data:{}});
  assert.equal(card.state,'draft');assert.equal(card.actor_initials,'JD');assert.equal(card.revision,1);
  const first=await counts();assert.equal(first.stock,initial.stock);assert.equal(first.stock_events,0);
  const creationRetry=await save(id,0,{x:1200,y:1400,data:{}});
  assert.equal(creationRetry.id,id);assert.deepEqual(await counts(),first);
  await assert.rejects(save(id,4,{data:{item_name:'Overwrites other crew'}}),/another device/);
  await assert.rejects(save(id,1,{data:{quantity:1.5}}),/whole number/);
  const bin=await one("select id from inventory_bins where bin_code='F30-000'");
  const data={item_name:'Workspace rotor',quantity:null,quantity_unit:'pcs',platform:'F30',stock_category:'Mobile',cart_code:'F30-A',inventory_bin_id:bin.id,notes:'Photo first, count later',label_media_id:'metric25x50'};
  card=await save(id,card.revision,{data});
  assert.equal(card.data.quantity,null);
  // Upload policy only permits objects under an existing active card.
  await assert.rejects(call("insert into storage.objects(bucket_id,name) values('otr-inventory-workspace',$1) returning id",[randomUUID()+'/bad.jpg']),/row-level security/);
  const path=id+'/'+randomUUID()+'.jpg';
  await call("insert into storage.objects(bucket_id,name) values('otr-inventory-workspace',$1) returning id",[path]);
  await assert.rejects(save(id,card.revision,{data:{photo_paths:[id+'/missing.jpg']}}),/upload must complete/);
  card=await save(id,card.revision,{data:{photo_paths:[path]}});
  const copyId=randomUUID();let copy=await duplicate(id,copyId);
  assert.notEqual(copy.tag_id,card.tag_id);assert.equal(copy.source_draft_id,id);assert.equal(copy.inventory_item_id,null);
  assert.deepEqual(copy.data,card.data);assert.equal(copy.x,card.x+36);
  const afterCopy=await counts();await duplicate(id,copyId);assert.deepEqual(await counts(),afterCopy);
  assert.equal(afterCopy.stock,initial.stock);
  copy=await save(copy.id,copy.revision,{x:2500,y:1800,data:{quantity:3}});
  assert.equal(copy.x,2500);assert.equal(copy.data.item_name,card.data.item_name);
  const stockTag=copy.tag_id;const previousRevision=copy.revision;
  copy=await commit(copy.id,copy.revision);
  assert.equal(copy.inventory_item_id,copy.id);
  let stock=await one('select * from inventory_items where id=$1',[copy.id]);
  assert.equal(stock.tag_id,stockTag);assert.equal(stock.quantity,3);assert.equal(stock.cart_code,'F30-A');
  assert.deepEqual(stock.source_metadata.photo_paths,[path]);assert.equal(stock.source_metadata.workspace_draft_id,copy.id);
  const committedCounts=await counts();await commit(copy.id,previousRevision);assert.deepEqual(await counts(),committedCounts);
  assert.equal(committedCounts.stock,initial.stock+1);assert.equal(committedCounts.stock_events,1);
  assert.equal((await one("select event_type from inventory_events where inventory_item_id=$1",[stock.id])).event_type,'add_stock');
  await assert.rejects(save(copy.id,copy.revision,{data:{quantity:100}}),/saved inventory record/);
  const movedCard=await save(copy.id,copy.revision,{x:2700,y:1900});assert.equal(movedCard.x,2700);
  // Copying a saved card reads the latest authoritative stock count.
  await call('select use_inventory_part($1,$2,1,$3,$4)',[stock.id,'F30-GOLDIE','JD',randomUUID()]);
  const freshCopy=await duplicate(copy.id,randomUUID());assert.equal(freshCopy.data.quantity,2);
  assert.equal(freshCopy.data.source_inventory_item_id,stock.id);
  const unknown=await commit(id,card.revision);
  stock=await one('select * from inventory_items where id=$1',[id]);assert.equal(stock.quantity,null);assert.equal(stock.status,'Uncounted');
  assert.equal(stock.verification_status,'Needs Review');assert.equal(stock.tag_id,card.tag_id);
  await assert.rejects(commit(freshCopy.id,null),/Invalid draft revision/);
  // A failing stock audit rolls back both stock creation and draft transition.
  await db.exec("create function fail_workspace_stock() returns trigger language plpgsql as $$begin raise exception 'injected audit failure';end$$; create trigger workspace_stock_failure after insert on inventory_items for each row execute function fail_workspace_stock();");
  const beforeFailure=await counts();
  await assert.rejects(commit(freshCopy.id,freshCopy.revision),/injected audit failure/);
  assert.deepEqual(await counts(),beforeFailure);assert.equal((await one('select state from inventory_workspace_drafts where id=$1',[freshCopy.id])).state,'draft');
  await db.exec('drop trigger workspace_stock_failure on inventory_items;');
  const archived=await save(freshCopy.id,freshCopy.revision,{state:'archived'});assert.equal(archived.state,'archived');
  await assert.rejects(commit(archived.id,archived.revision),/Restore/);
  await assert.rejects(call('delete from inventory_workspace_drafts where id=$1',[id]),/permission denied/);
  await assert.rejects(call("insert into inventory_workspace_events(draft_id,event_type,actor_initials,to_state) values($1,'draft_created','FAKE','{}') returning id",[id]),/permission denied/);
  await assert.rejects(call("update inventory_workspace_events set actor_initials='FAKE' returning id"),/permission denied/);
  assert.equal((await one("select count(*)::int as total from inventory_workspace_events where actor_initials<>upper(btrim(actor_initials))")).total,0);
  assert((await rows("select event_type from inventory_workspace_events where draft_id=$1",[id])).some(e=>e.event_type==='draft_committed'));
  assert.equal((await one("select nullif(current_setting('otr.actor_initials',true),'') as actor")).actor,null);
  console.log('PASS shared workspace PostgreSQL: no baseline changes, private immutable photos, initials, revision conflicts, retry-safe creation/duplication/commit, unique copy identity, separate draft counts, unknown stock, placement/photos/lineage, committed-card protection, archive and atomic rollback');
}finally{await db.close();}
